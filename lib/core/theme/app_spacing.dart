/// Veena Design System - Spacing
/// 
/// 8px grid system for consistent spacing throughout the app.
/// All spacing values are multiples of 4px for pixel-perfect alignment.
class AppSpacing {
  AppSpacing._();

  // ─────────────────────────────────────────────────────────────────
  // BASE SPACING UNITS
  // ─────────────────────────────────────────────────────────────────
  
  /// Extra small: 4px - tight spacing, icons
  static const double xs = 4.0;
  
  /// Small: 8px - base unit, compact elements
  static const double sm = 8.0;
  
  /// Medium: 16px - standard content spacing
  static const double md = 16.0;
  
  /// Large: 24px - section spacing
  static const double lg = 24.0;
  
  /// Extra large: 32px - major section separation
  static const double xl = 32.0;
  
  /// 2X large: 48px - screen-level padding
  static const double xxl = 48.0;

  // ─────────────────────────────────────────────────────────────────
  // SEMANTIC SPACING
  // ─────────────────────────────────────────────────────────────────
  
  /// Screen horizontal padding
  static const double screenPadding = 16.0;
  
  /// Card internal padding
  static const double cardPadding = 12.0;
  
  /// Space between list items
  static const double listItemSpacing = 12.0;
  
  /// Space between sections
  static const double sectionSpacing = 24.0;
  
  /// Grid gap for artwork grids
  static const double gridGap = 16.0;

  // ─────────────────────────────────────────────────────────────────
  // BORDER RADIUS
  // ─────────────────────────────────────────────────────────────────
  
  /// Small radius: 4px - buttons, chips
  static const double radiusSm = 4.0;
  
  /// Medium radius: 8px - cards, inputs
  static const double radiusMd = 8.0;
  
  /// Large radius: 12px - featured cards, modals
  static const double radiusLg = 12.0;
  
  /// Extra large radius: 16px - bottom sheets
  static const double radiusXl = 16.0;
  
  /// Full radius for circular elements
  static const double radiusFull = 999.0;

  // ─────────────────────────────────────────────────────────────────
  // COMPONENT SIZES
  // ─────────────────────────────────────────────────────────────────
  
  /// Mini player height
  static const double miniPlayerHeight = 64.0;
  
  /// Bottom navigation height
  static const double bottomNavHeight = 56.0;
  
  /// App bar height
  static const double appBarHeight = 56.0;
  
  /// Icon button size
  static const double iconButtonSize = 48.0;
  
  /// Small artwork size
  static const double artworkSm = 56.0;
  
  /// Medium artwork size
  static const double artworkMd = 120.0;
  
  /// Large artwork size (playlist detail)
  static const double artworkLg = 240.0;
}
